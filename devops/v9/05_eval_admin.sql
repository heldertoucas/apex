-- 12. Avaliacoes_Modulo
CREATE TABLE Avaliacoes_Modulo (
    ID_Avaliacao NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ID_Matricula NUMBER,
    ID_Modulo NUMBER,
    Nota_Valor NUMBER,
    Feedback_Texto CLOB,
    Aprovado CHAR(1) CHECK (Aprovado IN ('S','N')),
    CONSTRAINT FK_Avaliacao_Matricula FOREIGN KEY (ID_Matricula) REFERENCES Matriculas(ID_Matricula),
    CONSTRAINT FK_Avaliacao_Modulo FOREIGN KEY (ID_Modulo) REFERENCES Modulos(ID_Modulo)
);

-- 13. Badges_Conquistados
CREATE TABLE Badges_Conquistados (
    ID_Badge_Aluno NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ID_Matricula NUMBER,
    ID_Competencia NUMBER,
    Data_Conquista DATE DEFAULT SYSDATE,
    URL_Evidencia VARCHAR2(500),
    Token_Validacao VARCHAR2(100),
    CONSTRAINT FK_Badges_Matricula FOREIGN KEY (ID_Matricula) REFERENCES Matriculas(ID_Matricula),
    CONSTRAINT FK_Badges_Competencia FOREIGN KEY (ID_Competencia) REFERENCES Catalogo_Competencias(ID_Competencia)
);

-- 13a. Staging_Importacao
CREATE TABLE Staging_Importacao (
    ID_Staging NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    Data_Upload TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    Utilizador VARCHAR2(100),
    Nome_Excel VARCHAR2(255),
    Email_Excel VARCHAR2(255),
    NIF_Excel VARCHAR2(50),
    Curso_Excel VARCHAR2(255),
    Data_Excel VARCHAR2(50),
    Linha_Valida CHAR(1) CHECK (Linha_Valida IN ('S','N')),
    Mensagem_Erro VARCHAR2(4000),
    ID_Curso_Mapeado NUMBER,
    ID_Genero_Mapeado NUMBER
);

-- 14. Itens_Dossier_Turma
CREATE TABLE Itens_Dossier_Turma (
    ID_Item_Dossier NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ID_Turma NUMBER,
    ID_Tipo_Doc NUMBER,
    Presente CHAR(1) DEFAULT 'N' CHECK (Presente IN ('S','N')),
    URL_Ficheiro VARCHAR2(500),
    Validado_Por VARCHAR2(255),
    Data_Validacao DATE,
    Data_Upload DATE,
    Observacoes VARCHAR2(4000),
    CONSTRAINT FK_Dossier_Turma FOREIGN KEY (ID_Turma) REFERENCES Turmas(ID_Turma),
    CONSTRAINT FK_Dossier_TipoDoc FOREIGN KEY (ID_Tipo_Doc) REFERENCES Tipos_Documento_Dossier(ID_Tipo_Doc)
);

-- 15. Faturas_Formadores
CREATE TABLE Faturas_Formadores (
    ID_Fatura NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ID_Turma NUMBER,
    ID_Formador NUMBER,
    Num_Fatura VARCHAR2(50),
    Valor NUMBER,
    Mes_Ref VARCHAR2(7), -- YYYY-MM
    Estado VARCHAR2(20) CHECK (Estado IN ('EMITIDA', 'PAGA')),
    Data_Emissao DATE,
    Data_Contabilistica DATE,
    Data_Pagamento DATE,
    Observacoes CLOB,
    CONSTRAINT FK_Faturas_Turma FOREIGN KEY (ID_Turma) REFERENCES Turmas(ID_Turma),
    CONSTRAINT FK_Faturas_Formador FOREIGN KEY (ID_Formador) REFERENCES Entidades(ID_Entidade)
);

-- 16. Equipamentos_Alocados
CREATE TABLE Equipamentos_Alocados (
    ID_Alocacao NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ID_Turma NUMBER,
    ID_Tipo_Equipamento NUMBER,
    Quantidade NUMBER,
    Data_Entrega DATE,
    Data_Devolucao DATE,
    Estado_Conservacao VARCHAR2(200),
    Responsavel_Entrega VARCHAR2(200),
    Recebido_Por VARCHAR2(200),
    CONSTRAINT FK_EquipAlloc_Turma FOREIGN KEY (ID_Turma) REFERENCES Turmas(ID_Turma),
    CONSTRAINT FK_EquipAlloc_Tipo FOREIGN KEY (ID_Tipo_Equipamento) REFERENCES Tipos_Equipamento(ID_Tipo_Equipamento)
);
