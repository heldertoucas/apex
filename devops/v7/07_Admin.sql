-- 0. Garantir Lookups Necessários (Defensivo)
-- Caso não tenham sido criados anteriormente (ex: 01_Dominios.sql em falta)

-- 0.1 Tipos_Documento_Dossier
DECLARE
    v_count NUMBER;
BEGIN
    SELECT count(*) INTO v_count FROM user_tables WHERE table_name = 'TIPOS_DOCUMENTO_DOSSIER';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE Tipos_Documento_Dossier (
            ID_Tipo_Doc NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
            Codigo VARCHAR2(50) UNIQUE,
            Descricao VARCHAR2(200) NOT NULL,
            Obrigatorio CHAR(1) DEFAULT ''S'' CHECK (Obrigatorio IN (''S'',''N''))
        )';
    END IF;
END;
/

